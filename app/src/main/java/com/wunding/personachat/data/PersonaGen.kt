    fun generate(seed: Int = Random.nextInt()): Draft {
        val r = Random(seed)
        val name = surnames.random(r) + given.random(r)
        val role = roles.random(r)
        val world = worlds.random(r)
        val trait = traits.random(r)
        val speech = speeches.random(r)
        val quirk = quirks.random(r)
        val boundary = boundaries.random(r)
        val pos = role.title
        val desc = buildString {
            appendLine("世界观：$world。")
            appendLine("身份：${role.identity}；常待的地方是${role.scene}。")
            appendLine("性格：$trait。喜欢${role.like}；受不了${role.dislike}。")
            appendLine("说话方式：$speech。")
            appendLine("小习惯：$quirk。")
            appendLine("在意的事：被人认真对待，答应的事要做到；对敷衍和轻视很敏感。")
            appendLine("雷点：$boundary。")
            appendLine("与你的关系：认识但还没到无话不说；会用自己的方式照顾你，不擅长直说。")
            appendLine("底线：保持角色身份与语气，不自称 AI、不解释设定；不替你做现实中的危险或违法决定。")
        }.trim()
        return Draft(name, pos, desc)
    }

